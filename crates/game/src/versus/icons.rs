/// Draws the icon at `scale` pixels per cell and returns the space used.
pub fn draw(ui: &mut egui::Ui, u: Upgrade, scale: f32, lit: bool) -> egui::Response {
    let side = 8.0 * scale;
    let (rect, resp) = ui.allocate_exact_size(egui::vec2(side, side), egui::Sense::hover());
    let p = ui.painter();
    let ink = if lit { theme::INK } else { theme::DIM };
    let amber = if lit { theme::GOLD } else { theme::DIM };
    for (y, row) in bitmap(u).iter().enumerate() {
        for (x, ch) in row.bytes().enumerate() {
            let colour = match ch {
                b'#' => ink,
                b'o' => amber,
                _ => continue,
            };
            let min = rect.min + egui::vec2(x as f32 * scale, y as f32 * scale);
            p.rect_filled(
                egui::Rect::from_min_size(min, egui::vec2(scale, scale)),
                0.0,
                colour,
            );
        }
    }
    resp
}
